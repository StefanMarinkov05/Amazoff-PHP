    <h2>Ordering</h2>

    <h3>Do I need an account to order?</h3>
    <p>
        No. Checkout works as a guest. An account is worth having if you want
        your orders listed in one place afterwards — see
        <a href="/account/orders" wire:navigate>your orders</a> — and so your
        details are prefilled next time.
    </p>

    <h3>How do I know my order went through?</h3>
    <p>
        You are shown an order number on the confirmation page and sent the same
        by email. If you never reached a confirmation page, check
        <a href="/orders/track" wire:navigate>track an order</a> before ordering
        again, so you do not order twice.
    </p>

    <h3>Can I change or cancel an order?</h3>
    <p>
        Contact us with the order number as soon as possible. Before it is handed
        to the courier we can usually change or cancel it; afterwards it becomes
        a return.
    </p>

    <h2>Payment</h2>

    <h3>Why did my bank ask me to confirm the payment?</h3>
    <p>
        That is 3-D Secure, required by the card scheme for many cards. It is
        part of the payment, not something extra we ask for. Nothing is charged
        until you complete it.
    </p>

    <h3>My order says "still confirming" — is something wrong?</h3>
    <p>
        Usually not. The confirmation from your bank can arrive a few seconds
        after you return to the site. The order is already reserved and nothing
        more is needed from you. If it has not moved after a few minutes, get in
        touch with the order number.
    </p>

    <h3>Can I pay when the parcel arrives?</h3>
    <p>
        Yes — choose cash on delivery at checkout and pay the courier. See the
        <a href="/payment-information" wire:navigate>payment page</a>.
    </p>

    <h2>Delivery</h2>

    <h3>How long will it take?</h3>
    <p>
        Typically the next working day, one to two for smaller settlements. The
        <a href="/delivery" wire:navigate>delivery page</a> has the detail.
    </p>

    <h3>Where is my parcel?</h3>
    <p>
        Use <a href="/orders/track" wire:navigate>track an order</a> with your
        order number and the email you ordered with.
    </p>

    <h2>Returns</h2>

    <h3>How long do I have?</h3>
    <p>
        14 days from receiving the goods, in the condition you received them.
        The <a href="/terms" wire:navigate>terms</a> set out the exceptions and
        who pays return shipping.
    </p>

    <h3>When do I get my money back?</h3>
    <p>
        Once we have the return, the refund goes back to the method you paid
        with. Your bank decides how quickly it shows on your statement.
    </p>

    <h2>Anything else</h2>
    <p>
        Ask through the <a href="/contact" wire:navigate>contact form</a>.
    </p>
