    <p>
        This site sets a small number of cookies, all of them necessary for it to
        work. <strong>There is no advertising cookie, no analytics cookie, and no
        third-party tracker.</strong> That is why you are not asked to accept
        anything — there is nothing here to opt out of that would leave the site
        functioning.
    </p>

    <h2>What is set</h2>
    <ul>
        <li>
            <strong>Session cookie.</strong> Identifies your browsing session so
            your basket survives moving between pages, and so you stay signed in
            if you have an account. Expires when the session does.
        </li>
        <li>
            <strong>CSRF token cookie.</strong> A security measure. It lets the
            site verify that a form submission came from a page it served,
            rather than from another site acting as you.
        </li>
        <li>
            <strong>Stripe.</strong> When you reach the payment step, Stripe sets
            its own cookies to process the payment and detect fraud. These are
            set by Stripe, governed by Stripe's own policy, and are only
            involved once you are paying by card.
        </li>
    </ul>

    <h2>What is not set</h2>
    <p>
        No Google Analytics, no advertising pixels, no social-media trackers, no
        cross-site profiling. We do not know which other sites you visit and
        have no way to find out.
    </p>

    <h2>Blocking them</h2>
    <p>
        Your browser can block cookies for this site. The consequence is
        practical rather than legal: without the session cookie your basket will
        empty between pages and you will not be able to sign in or check out.
    </p>

