    <h2>Where we deliver</h2>
    <p>
        We ship across Bulgaria with Econt and Speedy. You choose the courier at
        checkout, and either to a courier office or to a street address.
    </p>

    <h2>Delivery options</h2>
    <ul>
        <li>
            <strong>To a courier office.</strong> Pick the office nearest you at
            checkout and collect when it arrives. Usually the cheapest option.
        </li>
        <li>
            <strong>To an address.</strong> The courier delivers to the street
            address you give at checkout.
        </li>
    </ul>

    <h2>Timing</h2>
    <p>
        Orders placed on a working day before the courier cut-off are handed over
        the same day. Delivery is typically the next working day, and one to two
        working days for smaller settlements. Weekends and public holidays are not
        working days for either courier.
    </p>
    <p>
        We hold your items the moment the order is placed, so an order confirmed
        today is not at risk of selling out while it is being prepared.
    </p>

    <h2>Delivery cost</h2>
    <p>
        The cost depends on the courier, the destination, and the weight of the
        parcel. The exact figure is shown at checkout before you pay — there is
        nothing added afterwards.
    </p>

    <h2>Tracking</h2>
    <p>
        Once your parcel is handed to the courier you can follow it on the
        <a href="/orders/track" wire:navigate>track an order</a> page using your
        order number and the email address you ordered with. If you have an
        account, your orders are also listed under
        <a href="/account/orders" wire:navigate>your orders</a>.
    </p>

    <h2>If something goes wrong</h2>
    <p>
        If a parcel is late, damaged, or does not arrive, tell us through the
        <a href="/contact" wire:navigate>contact form</a> with your order number
        and we will chase the courier on your behalf.
    </p>
</x-site.prose-page>
