    <p>
        This policy covers the data this shop collects. It is written to be read
        rather than to be comprehensive-by-volume; if something you need is not
        here, ask through the <a href="/contact" wire:navigate>contact form</a>.
    </p>

    <h2>What we collect, and why</h2>
    <ul>
        <li>
            <strong>Order details</strong> — your name, email address, phone
            number and delivery address. Needed to fulfil the order and hand it
            to a courier. This is the contract we have with you, not consent you
            can withdraw while the order is in progress.
        </li>
        <li>
            <strong>Account details</strong> — if you register, your name, email
            address and a hashed password. We never store the password itself.
        </li>
        <li>
            <strong>Payment records</strong> — the amount, currency, status and
            the reference Stripe gives us. <strong>No card data.</strong> Card
            numbers go from your browser to Stripe and never pass through this
            site.
        </li>
        <li>
            <strong>Reviews, contact messages, and newsletter signups</strong> —
            where you choose to send them.
        </li>
    </ul>

    <h2>How long we keep it</h2>
    <p>
        Order records are kept because we are required to: accounting and tax
        rules oblige us to retain proof of a sale, and that obligation outlives
        any request to delete it. Everything not tied to that obligation — a
        newsletter subscription, a contact message, an account you no longer
        want — can be removed on request.
    </p>
    <p>
        This means a deletion request does not erase your past orders. It removes
        your account and detaches what can be detached; the order history itself
        remains, because the law requires it to.
    </p>

    <h2>Who else sees it</h2>
    <ul>
        <li>
            <strong>Stripe</strong> — processes card payments. They receive what
            they need to take the payment.
        </li>
        <li>
            <strong>Econt and Speedy</strong> — receive the delivery address and
            phone number for the parcel they are carrying, and the amount to
            collect for a cash-on-delivery order.
        </li>
    </ul>
    <p>
        We do not sell your data, and we do not pass it to anyone for
        advertising.
    </p>

    <h2>Your rights</h2>
    <ul>
        <li>Ask what we hold about you, and get a copy.</li>
        <li>Correct anything that is wrong.</li>
        <li>Ask us to delete what we are not obliged to keep.</li>
        <li>Unsubscribe from the newsletter at any time.</li>
    </ul>
    <p>
        Send any of these through the
        <a href="/contact" wire:navigate>contact form</a> from the address on the
        account, so we can be reasonably sure the request is yours.
    </p>

    <h2>Security</h2>
    <p>
        Passwords are hashed, not encrypted — we cannot read them and cannot tell
        you what yours is. Traffic to this site is encrypted in transit. Staff
        access to customer data is limited by role, and every change to an order
        is recorded with who made it.
    </p>
